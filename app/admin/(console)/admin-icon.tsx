export type AdminIconName = keyof typeof glyphs;

type AdminIconProps = {
  name: AdminIconName | (string & {});
  className?: string;
  strokeWidth?: number;
  style?: React.CSSProperties;
};

export default function AdminIcon({ name, className, strokeWidth = 1.7, style }: AdminIconProps) {
  const icon = glyphs[name as AdminIconName] ?? glyphs.grid;
  return <HugeiconsIcon icon={icon} size={24} strokeWidth={strokeWidth} className={className} style={style} aria-hidden="true" />;
}
